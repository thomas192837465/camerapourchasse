export function StarRating({ average = 0, count }) {
  const rounded = Math.round(average);
  return (
    <span className="rating">
      <span className="stars">
        {[1, 2, 3, 4, 5].map((n) => (
          <StarIcon key={n} style={{ opacity: n <= rounded ? 1 : 0.35 }} />
        ))}
      </span>
      {typeof count === "number" ? `${count} avis` : null}
    </span>
  );
}
